"""Daily report generation service for structured pre-market intelligence briefs."""
import json
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import List, Dict, Any, Optional

from app.config import settings, BASE_DIR
from app.models.schemas import DailyReport, StockWatchItem, SentimentAnalysisResult
from app.utils.logging_config import logger

REPORTS_DIR = BASE_DIR / "reports"
if not REPORTS_DIR.exists():
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)


class ReportGenerator:
    """Creates, formats, and exports daily pre-market intelligence reports."""

    @staticmethod
    def generate_report(
        stocks_to_watch: List[StockWatchItem],
        analyses: List[SentimentAnalysisResult],
        market_session: str = "Pre-Market Session (US Eastern / NASDAQ)"
    ) -> DailyReport:
        """Constructs a DailyReport model from current market insights."""
        now = datetime.now(timezone.utc)
        date_str = now.strftime("%Y-%m-%d")
        report_id = f"RPT-{now.strftime('%Y%m%d-%H%M%S')}"

        # Macro summary
        bullish_count = sum(1 for s in stocks_to_watch if s.dominant_sentiment == "positive")
        bearish_count = sum(1 for s in stocks_to_watch if s.dominant_sentiment == "negative")
        neutral_count = len(stocks_to_watch) - bullish_count - bearish_count

        overview = (
            f"Pre-market analysis tracking {len(stocks_to_watch)} primary watchlist assets. "
            f"Sentiment distribution reveals {bullish_count} bullish catalysts, {bearish_count} bearish risk events, "
            f"and {neutral_count} neutral/mixed developments. Key themes are driven by enterprise AI infrastructure, "
            f"cloud partnerships, and automotive regulatory inquiries."
        )

        # High impact events
        high_impact = []
        for a in analyses[:5]:
            high_impact.append({
                "symbol": a.stock_symbol,
                "company": a.company_name,
                "category": a.event_category,
                "sentiment": a.sentiment,
                "score": a.sentiment_score,
                "headline": a.short_summary,
                "evidence": a.evidence,
                "source_url": a.original_url,
                "published_at": a.published_at
            })

        # General market risks
        risks = [
            "Macroeconomic monetary policy announcements and interest rate fluctuations.",
            "Potential pre-market gap-open volatility and liquidity imbalances before standard trading hours.",
            "Headline risk from evolving regulatory inquiries and antitrust reviews."
        ]

        disclaimer = (
            "DISCLAIMER: This report is generated by the AI-Powered Stock Market Insights Bot "
            "for educational, academic, and informational research purposes only. "
            "It does NOT constitute financial, investment, legal, or trading advice. "
            "Past performance and news sentiment do not guarantee future stock price results. "
            "Never execute live trades based solely on automated sentiment signals."
        )

        freshness = (
            f"Data collected as of {now.strftime('%Y-%m-%d %H:%M:%S UTC')}. "
            "Market data snapshots and technical indicators reflect the most recent available closing "
            "and pre-market quotes. Feeds may be delayed in accordance with provider terms."
        )

        report = DailyReport(
            report_id=report_id,
            report_date=date_str,
            generated_at=now.isoformat(),
            market_session=market_session,
            market_overview=overview,
            stocks_to_watch=stocks_to_watch,
            high_impact_events=high_impact,
            risk_factors=risks,
            disclaimer=disclaimer,
            data_freshness_warning=freshness
        )

        return report

    @staticmethod
    def to_markdown(report: DailyReport) -> str:
        """Converts a DailyReport into a beautifully styled Markdown document."""
        lines = [
            f"# Daily Market Insights Briefing: {report.report_date}",
            f"**Report ID**: `{report.report_id}` | **Session**: {report.market_session} | **Generated**: {report.generated_at[:19]} UTC\n",
            "## 1. Market Overview & Pre-Market Tone",
            f"{report.market_overview}\n",
            "## 2. Top Stocks to Watch (Ranked by Priority Score)",
            "| Rank | Symbol | Company | Dominant Sentiment | Priority Score | Recent Price | RSI (14) | Technical Bias |",
            "| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |"
        ]

        for s in report.stocks_to_watch:
            rsi_val = f"{s.rsi:.1f}" if s.rsi is not None else "N/A"
            price_val = f"${s.recent_price:.2f}" if s.recent_price is not None else "N/A"
            lines.append(
                f"| #{s.rank} | **{s.symbol}** | {s.company_name} | `{s.dominant_sentiment.upper()}` | {s.priority_score:.2f} | {price_val} | {rsi_val} | {s.technical_bias} |"
            )

        lines.append("\n### Detailed Stock Watch Catalysts & Reasoning\n")
        for s in report.stocks_to_watch:
            lines.append(f"#### #{s.rank} - {s.company_name} ({s.symbol})")
            lines.append(f"- **Key Headline**: {s.key_headline}")
            lines.append(f"- **Selection Rationale**: {s.selection_rationale}")
            if s.material_risks:
                lines.append(f"- **Material Risks**: {', '.join(s.material_risks)}")
            if s.article_urls:
                lines.append(f"- **Source Reference**: [Original Article Link]({s.article_urls[0]})")
            lines.append("")

        lines.append("## 3. High-Impact News Developments")
        for ev in report.high_impact_events:
            lines.append(f"- **[{ev['symbol']}] {ev['headline']}**")
            lines.append(f"  - *Category*: {ev['category']} | *Sentiment*: {ev['sentiment']} ({ev['score']:+0.2f})")
            lines.append(f"  - *Supporting Evidence*: \"{ev['evidence']}\"")
            lines.append(f"  - *Source*: [{ev['source_url']}]({ev['source_url']})")
            lines.append("")

        lines.append("## 4. Key Market Risk Factors")
        for r in report.risk_factors:
            lines.append(f"- {r}")

        lines.append(f"\n> **Data Freshness Note**: {report.data_freshness_warning}\n")
        lines.append(f"> **Educational Disclaimer**: {report.disclaimer}\n")

        return "\n".join(lines)

    @classmethod
    def save_report(cls, report: DailyReport) -> Path:
        """Saves report as Markdown and JSON to the reports directory."""
        md_content = cls.to_markdown(report)
        filename_base = f"{report.report_date}_{report.report_id}"
        
        md_path = REPORTS_DIR / f"{filename_base}.md"
        json_path = REPORTS_DIR / f"{filename_base}.json"

        with open(md_path, "w", encoding="utf-8") as f:
            f.write(md_content)

        with open(json_path, "w", encoding="utf-8") as f:
            f.write(report.model_dump_json(indent=2))

        logger.info(f"Report saved to {md_path} and {json_path}")
        return md_path
